export function getResultMatch(code: MbtiCode) {
  const [type, taste] = code.split('-') as [MbtiType, MbtiTaste];
  return {
    type,
    taste,
    profile: profiles[type],
    whisky: matches[type]?.[taste],
    isOriginal: originalTaste[type] === taste,
  };
}

export function isMbtiCode(code: string | null): code is MbtiCode {
  return (
    !!code &&
    /^((INTJ|INTP|ENTJ|ENTP|INFJ|INFP|ENFJ|ENFP|ISTJ|ISFJ|ESTJ|ESFJ|ISTP|ISFP|ESTP|ESFP)-(A|B|C))$/.test(
      code,
    )
  );
}
